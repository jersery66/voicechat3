"""Start the app with the paths that were found at install time.

Site-Start.bat calls this instead of exporting variables itself: batch files are
read in the console code page, so a Chinese install path (D:\\戒毒所\\...) written
as GBK breaks under chcp 65001 and vice versa. JSON has exactly one encoding, and
the child process inherits whatever this sets.

Order of precedence (later wins):
1. site-env.json       — generated by site_autoconfig.py --install
2. site-config.cmd     — hand-edited by the operator (device index, scale)
3. anything already in the environment

    python scripts\\launch\\site_launch.py              # 正常启动
    python scripts\\launch\\site_launch.py --check      # 只打印将要设置的环境
    python scripts\\launch\\site_launch.py -- -PreflightOnly   # 透传给原启动脚本
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENV_FILE = ROOT / "site-env.json"
USER_CONFIG = ROOT / "site-config.cmd"
LAUNCHER = ROOT / "start_voicechat3_offline.bat"
_SET_LINE = re.compile(r'^\s*set\s+"?([A-Za-z_][A-Za-z0-9_]*)=([^"\r\n]*)"?\s*$', re.IGNORECASE)


def load_generated() -> dict[str, str]:
    if not ENV_FILE.is_file():
        return {}
    try:
        payload = json.loads(ENV_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"WARNING: {ENV_FILE.name} 无法解析（{exc}），改用自动探测")
        return {}
    env = payload.get("env") or {}
    return {str(k): str(v) for k, v in env.items() if v}


def load_user_config() -> dict[str, str]:
    """Read `set "NAME=VALUE"` lines. Values must be ASCII (device index, scale)."""
    if not USER_CONFIG.is_file():
        return {}
    settings: dict[str, str] = {}
    text = USER_CONFIG.read_text(encoding="utf-8", errors="replace")
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.lower().startswith("rem"):
            continue
        match = _SET_LINE.match(line)
        if not match:
            continue
        name, value = match.group(1), match.group(2).strip()
        if not value:
            continue
        if any(ord(ch) > 127 for ch in value):
            # Batch is read in the console code page; a CJK value here would be
            # mangled depending on chcp. Numbers (device index) are safe.
            print(f"WARNING: site-config.cmd 里 {name} 的值含中文，已忽略：{value}")
            continue
        settings[name] = value
    return settings


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    check_only = "--check" in args
    if check_only:
        args.remove("--check")
    passthrough: list[str] = []
    if "--" in args:
        split = args.index("--")
        passthrough, args = args[split + 1:], args[:split]
    passthrough.extend(args)

    generated = load_generated()
    user = load_user_config()
    effective = {**generated, **user}

    if check_only:
        print(f"程序目录：{ROOT}")
        print(f"环境文件：{ENV_FILE.name}  {'存在' if ENV_FILE.is_file() else '缺失'}")
        print("将要设置的环境变量：")
        for name, value in sorted(effective.items()):
            print(f"  {name} = {value}")
        if not effective:
            print("  （无，依赖 config.py 自动探测）")
        print(f"启动脚本：{LAUNCHER}   {'存在' if LAUNCHER.is_file() else '缺失！'}")
        return 0

    if not LAUNCHER.is_file():
        print(f"找不到启动脚本：{LAUNCHER}")
        print("请确认本文件夹是完整的程序目录（应包含 start_voicechat3_offline.bat）。")
        return 1

    env = dict(os.environ)
    env.update(effective)
    for name, value in effective.items():
        print(f"[site] {name} = {value}", flush=True)

    # Run the original launcher unchanged; it starts the model service, runs the
    # preflight and opens the window.
    try:
        completed = subprocess.run(["cmd", "/c", str(LAUNCHER), *passthrough],
                                   cwd=str(ROOT), env=env)
    except KeyboardInterrupt:
        return 130
    return int(completed.returncode or 0)


if __name__ == "__main__":
    sys.exit(main())
